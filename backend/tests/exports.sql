BEGIN;
CREATE FUNCTION pg_temp.check_export(ok boolean) RETURNS void LANGUAGE plpgsql AS $$
BEGIN IF ok IS DISTINCT FROM true THEN RAISE EXCEPTION 'Export assertion failed'; END IF; END $$;
INSERT INTO auth.users VALUES ('00000000-0000-0000-0000-000000000081'),('00000000-0000-0000-0000-000000000082');
INSERT INTO app.profiles(id,user_id) SELECT id,id FROM auth.users WHERE id::text LIKE '%00000000008_';
DO $$
DECLARE a uuid := '00000000-0000-0000-0000-000000000081'; b uuid := '00000000-0000-0000-0000-000000000082';
 g uuid := gen_random_uuid(); o uuid := gen_random_uuid(); w uuid := gen_random_uuid(); ticket jsonb; result jsonb; export_id uuid;
BEGIN
 INSERT INTO app.garments(id,user_id,name,category,price_grosz) VALUES(g,a,'Owned','top',80000);
 INSERT INTO app.garments(user_id,name,category,price_grosz) VALUES(b,'Other owner','top',123);
 INSERT INTO app.outfits(id,user_id,name) VALUES(o,a,'Outfit');
 INSERT INTO app.planned_outfits(user_id,outfit_id,planned_on) VALUES(a,o,current_date+1);
 INSERT INTO app.wear_events(id,user_id,worn_on,timezone,client_request_id) VALUES(w,a,current_date-1,'Europe/Warsaw',gen_random_uuid());
 INSERT INTO app.wear_event_items(user_id,wear_event_id,garment_id) VALUES(a,w,g);
 INSERT INTO app.garment_images(user_id,garment_id,variant,object_key,status) VALUES(a,g,'original',g::text||'/original.jpg','ready');
 PERFORM set_config('request.jwt.claim.sub',a::text,true);
 ticket := app.api_v1_request_export('{}');
 export_id := (ticket->'data'->>'id')::uuid;
 PERFORM pg_temp.check_export(ticket->'data' = app.api_v1_request_export('{}')->'data');
 PERFORM pg_temp.check_export((ticket->'data'->>'expires_at')::timestamptz <= clock_timestamp()+interval '15 minutes');
 result := app.export_snapshot(a,export_id);
 PERFORM pg_temp.check_export(jsonb_array_length(result->'garments')=1);
 PERFORM pg_temp.check_export(result->'garments'->0->>'price_grosz'='80000');
 PERFORM pg_temp.check_export(jsonb_array_length(result->'wear_events')=1 AND jsonb_array_length(result->'wear_event_items')=1);
 PERFORM pg_temp.check_export(jsonb_array_length(result->'planned_outfits')=1 AND jsonb_array_length(result->'photos')=1);
 PERFORM pg_temp.check_export(NOT result ?| ARRAY['ai_jobs','subscription_events','sync_operations','operator_audit']);
 PERFORM pg_temp.check_export(app.export_snapshot(b,export_id) IS NULL);
 PERFORM pg_temp.check_export(app.export_access(a,export_id,NULL,NULL));
 PERFORM pg_temp.check_export(NOT app.export_access(b,export_id,NULL,NULL));
 PERFORM pg_temp.check_export(app.export_access(a,export_id,(result->'photos'->0->>'id')::uuid,g::text||'/original.jpg'));
 PERFORM pg_temp.check_export(NOT app.export_access(a,export_id,(result->'photos'->0->>'id')::uuid,'wrong-key'));
 UPDATE api_private.exports SET expires_at=clock_timestamp()-interval '1 second' WHERE user_id=a;
 PERFORM pg_temp.check_export(app.export_snapshot(a,export_id) IS NULL);
 PERFORM pg_temp.check_export(NOT app.export_access(a,export_id,NULL,NULL));
 ticket := app.api_v1_request_export('{}');
 PERFORM pg_temp.check_export((ticket->'data'->>'id')::uuid <> export_id);
 export_id := (ticket->'data'->>'id')::uuid;
 UPDATE app.profiles SET deleted_at=clock_timestamp() WHERE user_id=a;
 PERFORM pg_temp.check_export(app.export_snapshot(a,export_id) IS NULL);
 PERFORM pg_temp.check_export(NOT app.export_access(a,export_id,NULL,NULL));
 DELETE FROM auth.users WHERE id=a;
 PERFORM pg_temp.check_export(NOT EXISTS(SELECT FROM api_private.exports WHERE user_id=a));
END $$;
SELECT pg_temp.check_export(NOT has_table_privilege('authenticated','api_private.exports','SELECT'));
SELECT pg_temp.check_export(NOT has_function_privilege('authenticated','app.export_snapshot(uuid,uuid)','EXECUTE'));
SELECT pg_temp.check_export(NOT has_function_privilege('authenticated','app.export_access(uuid,uuid,uuid,text)','EXECUTE'));
SELECT pg_temp.check_export(NOT has_function_privilege('anon','app.api_v1_request_export(jsonb)','EXECUTE'));
ROLLBACK;
